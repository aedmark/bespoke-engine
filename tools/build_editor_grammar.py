#!/usr/bin/env python3
"""Generate the BeSpoke TextMate grammar from the lexer keyword map."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
LEXER = ROOT / "src" / "compiler" / "lexer.zig"
GRAMMAR = ROOT / "editors" / "vscode" / "syntaxes" / "bespoke.tmLanguage.json"
MAP = re.compile(
    r"^pub fn keyword_map\(\).*?\{\n"
    r"    return std\.StaticStringMap\(TokenTag\)\.initComptime\(\.\{\n"
    r"(.*?)^    \}\);\n\}",
    re.MULTILINE | re.DOTALL,
)
ENTRY = re.compile(r'\.\{\s*"([A-Za-z][A-Za-z0-9_-]*)",\s*\.kw_[a-z0-9_]+\s*\},')


def read_keywords(source: str) -> list[str]:
    match = MAP.search(source)
    if not match:
        raise ValueError("cannot find the lexer keyword map")
    words = []
    for row in match[1].splitlines():
        row = row.partition("//")[0].strip()
        if not row:
            continue
        entry = ENTRY.fullmatch(row)
        if not entry:
            raise ValueError(f"unsupported lexer keyword row: {row}")
        words.append(entry[1])
    if not words or len(words) != len(set(words)):
        raise ValueError("the lexer keyword map is empty or repeats a spelling")
    return sorted(words)


def render(words: list[str]) -> str:
    # The first matching rule wins at the same start position. The identifier
    # rule consumes the entire name, so a keyword inside Well-wait cannot match.
    keyword = "(?:" + "|".join(re.escape(word) for word in words) + ")(?![A-Za-z0-9_-])"
    grammar = {
        "information_for_contributors": [
            "Generated by tools/build_editor_grammar.py. Edit the generator, not this file."
        ],
        "name": "BeSpoke",
        "scopeName": "source.bespoke",
        "patterns": [
            {"name": "comment.line.bespoke", "match": r"[#~].*$"},
            {"name": "string.quoted.double.bespoke", "begin": '"', "end": '"'},
            {"name": "keyword.other.bespoke", "match": keyword},
            {"name": "constant.numeric.dice.bespoke", "match": r"[0-9]+d[0-9]*"},
            {"name": "constant.numeric.integer.bespoke", "match": r"[0-9]+"},
            {"name": "variable.other.bespoke", "match": r"[A-Za-z][A-Za-z0-9_-]*|_[A-Za-z0-9_]+"},
            {"name": "constant.language.wildcard.bespoke", "match": "_"},
            {"name": "keyword.operator.comparison.bespoke", "match": r">=|<=|==|!=|[<>=]"},
            {"name": "punctuation.separator.bespoke", "match": r"[,:\[\]()]"},
        ],
    }
    return json.dumps(grammar, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in grammar is stale")
    args = parser.parse_args()
    try:
        expected = render(read_keywords(LEXER.read_text(encoding="utf-8")))
    except (OSError, ValueError) as err:
        parser.exit(1, f"cannot generate editor grammar: {err}\n")
    path = GRAMMAR.relative_to(ROOT)
    if args.check:
        if not GRAMMAR.is_file() or GRAMMAR.read_text(encoding="utf-8") != expected:
            parser.exit(1, f"{path} is stale; run python3 tools/build_editor_grammar.py\n")
        print(f"{path} matches the lexer")
    else:
        GRAMMAR.parent.mkdir(parents=True, exist_ok=True)
        GRAMMAR.write_text(expected, encoding="utf-8", newline="\n")
        print(f"generated {path}")


if __name__ == "__main__":
    main()
