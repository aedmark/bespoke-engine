#!/usr/bin/env python3
"""Generate the showcase gallery and the standalone proof pages.

    zig build wasm-proofs harbour
    python3 tools/build_site.py
    python3 tools/build_site.py --check

The homepage links to one page per proof and embeds the generated Harbour page. The proof pages
carry bespoke-proofs.wasm and run from file://. Edit the inputs, not the generated regions.
"""
from __future__ import annotations

import argparse
import base64
import html as html_lib
import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML_PATH = ROOT / "site" / "index.html"
HARBOUR_PATH = ROOT / "site" / "harbour.html"
HARBOUR_ARTIFACT = ROOT / "zig-out" / "harbour" / "index.html"
SUNKEN_VAULT_PATH = ROOT / "site" / "sunken-vault.html"
SUNKEN_VAULT_ARTIFACT = ROOT / "zig-out" / "sunken-vault" / "index.html"
# What each built game page is made from. A build older than any of these is stale: the check
# would otherwise compare the committed page with an old build and pass, as it did for the
# 1.2.0 release commit, which CI (building fresh) then failed.
ENGINE_INPUTS = (ROOT / "src", ROOT / "build.zig", ROOT / "build.zig.zon", ROOT / "LICENSE")
HARBOUR_INPUTS = ENGINE_INPUTS + (ROOT / "scenarios" / "harbour",)
SUNKEN_VAULT_INPUTS = ENGINE_INPUTS + (
    ROOT / "scenarios" / "sunken_vault",
    ROOT / "tools" / "build_sunken_vault.py",
    ROOT / "tools" / "pack_game_page.py",
)
# The standalone proof pages (D-086, D-094, D-122): one deck each, a shared wrapper, the same module.
PROOF_PAGE_NAMES = (
    "tavern.html",
    "pips.html",
    "beard.html",
    "village.html",
    "donkey.html",
    "tides.html",
    "grog.html",
    "barbs.html",
    "saltmarket.html",
    "weathercock.html",
    "bell-tower.html",
    "fire-escape.html",
    "observatory.html",
    "valerius.html",
    "lamplighter.html",
    "long-gallery.html",
    "word-foundry.html",
    "cinder-table.html",
    "tide-beacon.html",
)
PROOF_PAGE_PATHS = tuple(ROOT / "site" / name for name in PROOF_PAGE_NAMES)
PROOF_PAGE_JS_PATH = Path(__file__).with_name("proof_page.js")
ENGINE_AUDIO_JS_PATH = Path(__file__).with_name("engine_audio.js")
WASM_ARTIFACT = ROOT / "zig-out" / "bin" / "bespoke-proofs.wasm"
START_MARKER = "<!-- SITE_SIMULATOR_START -->"
END_MARKER = "<!-- SITE_SIMULATOR_END -->"
PLACEHOLDER = "__BESPOKE_PROOFS_WASM_BASE64__"
GALLERY_PATH = Path(__file__).with_name("site_gallery.json")
GALLERY_START = "<!-- SITE_GALLERY_START -->"
GALLERY_END = "<!-- SITE_GALLERY_END -->"


def load_wasm(path: Path = WASM_ARTIFACT) -> bytes:
    try:
        payload = path.read_bytes()
    except FileNotFoundError as exc:
        raise SystemExit(
            f"proof WebAssembly module not found at {path}; run `zig build wasm-proofs` first"
        ) from exc
    if not payload.startswith(b"\0asm"):
        raise SystemExit(f"{path} is not a WebAssembly module")
    return payload


def render_page(html: str, wrapper: str, payload: bytes, wrapper_path: Path = PROOF_PAGE_JS_PATH) -> str:
    if html.count(START_MARKER) != 1 or html.count(END_MARKER) != 1:
        raise SystemExit("the page needs exactly one simulator start and end marker")
    start = html.index(START_MARKER)
    start = html.rfind("\n", 0, start) + 1
    end = html.index(END_MARKER, start) + len(END_MARKER)
    if PLACEHOLDER not in wrapper:
        raise SystemExit(f"{wrapper_path} is missing {PLACEHOLDER}")
    encoded = base64.b64encode(payload).decode("ascii")
    script = textwrap.indent(wrapper.replace(PLACEHOLDER, encoded, 1), "    ")
    # The shared AudioWorklet player (P34-05) goes first; the page script uses it.
    audio = textwrap.indent(ENGINE_AUDIO_JS_PATH.read_text(encoding="utf-8"), "    ")
    block = (
        f"  {START_MARKER}\n"
        f"  <!-- Generated by tools/build_site.py from tools/{ENGINE_AUDIO_JS_PATH.name}, tools/{wrapper_path.name}, and "
        "zig-out/bin/bespoke-proofs.wasm. -->\n"
        "  <script>\n"
        f"{audio}"
        "  </script>\n"
        "  <script>\n"
        f"{script}"
        "  </script>\n"
        f"  {END_MARKER}"
    )
    return html[:start] + block + html[end:]


def replace_region(html: str, start_marker: str, end_marker: str, block: str, what: str) -> str:
    if html.count(start_marker) != 1 or html.count(end_marker) != 1:
        raise SystemExit(f"site/index.html needs exactly one {what} start and end marker")
    start = html.rfind("\n", 0, html.index(start_marker)) + 1
    end = html.index(end_marker, start) + len(end_marker)
    return html[:start] + block + html[end:]


def render_gallery_block(entries: list[dict]) -> str:
    cards = []
    for number, entry in enumerate(entries, start=1):
        esc = lambda value: html_lib.escape(value, quote=True)  # noqa: E731
        page = entry["page"]
        if page not in PROOF_PAGE_NAMES:
            raise SystemExit(f"unknown standalone proof page: {page}")
        cards.append(
            f'        <div class="scenario-card gallery-card" id="proof-{esc(entry["id"])}">\n'
            '          <div class="scenario-info">\n'
            f'            <span class="scenario-tag">Proof {number:02d} · {esc(entry["tag"])}</span>\n'
            f'            <h3 class="scenario-heading">{esc(entry["title"])}</h3>\n'
            f'            <p class="scenario-text">{esc(entry["blurb"])}</p>\n'
            '          </div>\n'
            '          <div class="gallery-actions">\n'
            f'            <a class="sim-btn" href="{esc(page)}">Play this proof</a>\n'
            '          </div>\n'
            '        </div>\n'
        )
    return (
        f"      {GALLERY_START}\n"
        "      <!-- Generated by tools/build_site.py from tools/site_gallery.json. -->\n"
        '      <div class="scenario-grid">\n'
        + "".join(cards)
        + "      </div>\n"
        f"      {GALLERY_END}"
    )


def gallery_entries() -> list[dict]:
    return json.loads(GALLERY_PATH.read_text(encoding="utf-8"))["proofs"]


def render_site(html: str) -> str:
    return replace_region(html, GALLERY_START, GALLERY_END, render_gallery_block(gallery_entries()), "gallery")


def newest_input(inputs) -> tuple[float, Path] | None:
    """The most recently changed file among `inputs` (files, or folders walked whole)."""
    newest = None
    for root in inputs:
        files = [root] if root.is_file() else [f for f in root.rglob("*") if f.is_file() and "__pycache__" not in f.parts]
        for f in files:
            stamp = (f.stat().st_mtime, f)
            if newest is None or stamp[0] > newest[0]:
                newest = stamp
    return newest


def require_fresh(artifact: Path, inputs, rebuild: str) -> None:
    """Refuses a built page older than anything it is made from."""
    newest = newest_input(inputs)
    if newest is not None and artifact.exists() and artifact.stat().st_mtime < newest[0]:
        raise SystemExit(f"{shown(artifact)} is older than {shown(newest[1])}; rebuild it with `{rebuild}` first")


def shown(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def load_harbour(path: Path = HARBOUR_ARTIFACT) -> str:
    if path == HARBOUR_ARTIFACT:
        require_fresh(path, HARBOUR_INPUTS, "zig build harbour")
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise SystemExit(f"Harbour page not found at {path}; run `zig build harbour` first") from exc


def load_sunken_vault(path: Path = SUNKEN_VAULT_ARTIFACT) -> str:
    if path == SUNKEN_VAULT_ARTIFACT:
        require_fresh(path, SUNKEN_VAULT_INPUTS, "python3 tools/build_sunken_vault.py --force zig-out/sunken-vault/index.html")
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError as exc:
        raise SystemExit(
            f"Sunken Vault page not found at {path}; run `python3 tools/build_sunken_vault.py --force zig-out/sunken-vault/index.html` first"
        ) from exc


def render_proof_page(html: str) -> str:
    """A standalone proof page rendered from the current module (D-086, D-094, D-122)."""
    return render_page(html, PROOF_PAGE_JS_PATH.read_text(encoding="utf-8"), load_wasm(), PROOF_PAGE_JS_PATH)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the showcase pages are current")
    args = parser.parse_args(argv)

    payload = load_wasm()
    rendered = []
    for path, render in [(HTML_PATH, render_site)] + [(p, render_proof_page) for p in PROOF_PAGE_PATHS]:
        html = path.read_text(encoding="utf-8")
        rendered.append((path, html, render(html)))
    inside = HARBOUR_PATH.read_text(encoding="utf-8") if HARBOUR_PATH.exists() else None
    rendered.append((HARBOUR_PATH, inside, load_harbour()))
    sunken = SUNKEN_VAULT_PATH.read_text(encoding="utf-8") if SUNKEN_VAULT_PATH.exists() else None
    rendered.append((SUNKEN_VAULT_PATH, sunken, load_sunken_vault()))

    if args.check:
        stale = [path for path, html, page in rendered if page != html]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; run `python3 tools/build_site.py`", file=sys.stderr)
        if stale:
            return 1
        print(f"{len(rendered)} showcase pages are current (proof Wasm: {len(payload):,} bytes)")
        return 0

    for path, _, page in rendered:
        path.write_text(page, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)} ({len(page.encode('utf-8')):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
