#!/usr/bin/env python3
"""Embed the proof WebAssembly module and browser wrapper into site/index.html.

    zig build wasm-proofs
    python3 tools/build_site.py
    python3 tools/build_site.py --check

The showcase page remains a single self-contained file that runs from file://.
Edit tools/site_simulator.js, not the generated script region in site/index.html.
"""
import argparse
import base64
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML_PATH = ROOT / "site" / "index.html"
SIMULATOR_JS_PATH = Path(__file__).with_name("site_simulator.js")
WASM_ARTIFACT = ROOT / "zig-out" / "bin" / "bespoke-proofs.wasm"
START_MARKER = "<!-- SITE_SIMULATOR_START -->"
END_MARKER = "<!-- SITE_SIMULATOR_END -->"
PLACEHOLDER = "__BESPOKE_PROOFS_WASM_BASE64__"


def load_wasm(path: Path = WASM_ARTIFACT) -> bytes:
    try:
        payload = path.read_bytes()
    except FileNotFoundError as exc:
        raise SystemExit(
            f"proof WebAssembly module not found at {path}; run `zig build wasm-proofs` first"
        ) from exc
    if not payload.startswith(b"\0asm"):
        raise SystemExit(f"{path} is not a WebAssembly module")
    return payload


def render_page(html: str, wrapper: str, payload: bytes) -> str:
    if html.count(START_MARKER) != 1 or html.count(END_MARKER) != 1:
        raise SystemExit("site/index.html needs exactly one simulator start and end marker")
    start = html.index(START_MARKER)
    start = html.rfind("\n", 0, start) + 1
    end = html.index(END_MARKER, start) + len(END_MARKER)
    if PLACEHOLDER not in wrapper:
        raise SystemExit(f"{SIMULATOR_JS_PATH} is missing {PLACEHOLDER}")
    encoded = base64.b64encode(payload).decode("ascii")
    script = textwrap.indent(wrapper.replace(PLACEHOLDER, encoded, 1), "    ")
    block = (
        f"  {START_MARKER}\n"
        "  <!-- Generated by tools/build_site.py from tools/site_simulator.js and "
        "zig-out/bin/bespoke-proofs.wasm. -->\n"
        "  <script>\n"
        f"{script}"
        "  </script>\n"
        f"  {END_MARKER}"
    )
    return html[:start] + block + html[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify site/index.html is current")
    args = parser.parse_args(argv)

    payload = load_wasm()
    wrapper = SIMULATOR_JS_PATH.read_text(encoding="utf-8")
    html = HTML_PATH.read_text(encoding="utf-8")
    rendered = render_page(html, wrapper, payload)

    if args.check:
        if rendered != html:
            print("site/index.html is stale; run `python3 tools/build_site.py`", file=sys.stderr)
            return 1
        print(f"site/index.html embeds bespoke-proofs.wasm ({len(payload):,} bytes)")
        return 0

    HTML_PATH.write_text(rendered, encoding="utf-8")
    print(f"embedded {len(payload):,} bytes into {HTML_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
