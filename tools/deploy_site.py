#!/usr/bin/env python3
"""Export the showcase site for static hosting (P30-02, D-067, D-074).

    zig build wasm-proofs && python3 tools/build_site.py
    python3 tools/deploy_site.py export [--site-url https://NAME.neocities.org/]

`export` writes dist/site/: site/index.html with sharing metadata and a service-worker
registration added, and sw.js, which precaches the page under a cache named after its
content hash so each new upload replaces the last one. The repository's site/index.html is
not changed and still opens from file://. Export refuses a stale page (see
tools/build_site.py). Uploading dist/site/ is done by hand (D-074).
"""
from __future__ import annotations

import argparse
import hashlib
import html
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE_HTML = ROOT / "site" / "index.html"
# The standalone duel page (D-086), copied beside index.html; it carries its own sharing tags.
BARBS_HTML = ROOT / "site" / "barbs.html"
DEFAULT_OUT = ROOT / "dist" / "site"
HEAD_MARKER = "<!-- DEPLOY_METADATA -->"
BODY_MARKER = "<!-- DEPLOY_SERVICE_WORKER -->"

SERVICE_WORKER = """// Generated by tools/deploy_site.py. Precaches the showcase page so a return visit works
// offline. The cache name carries the page's content hash: a new deploy installs a new cache
// and deletes the old one, so visitors never keep a stale page once they are online.
const CACHE = 'bespoke-site-__HASH__';
const PRECACHE = ['./', 'index.html'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((n) => n.startsWith('bespoke-site-') && n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim())
  );
});

// Network first, so an online visitor always sees the deployed page; the cache answers only
// when the network fails.
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(() => caches.match(request).then((hit) => hit || caches.match('index.html')))
  );
});
"""

REGISTRATION = """  <script>
    // Offline cache (tools/deploy_site.py). Service workers need http(s); a page opened from
    // file:// skips this.
    if ('serviceWorker' in navigator && location.protocol.startsWith('http')) {
      navigator.serviceWorker.register('sw.js').catch(() => {});
    }
  </script>
"""


class DeployError(Exception):
    """A refusal the user can act on; printed without a traceback."""


def load_build_site():
    spec = importlib.util.spec_from_file_location("build_site", ROOT / "tools" / "build_site.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def require_current_page(page: str) -> None:
    """The exported page must be what build_site.py would write from the current module."""
    build_site = load_build_site()
    try:
        current = build_site.render_site(page)
    except SystemExit as exc:
        raise DeployError(str(exc)) from exc
    if current != page:
        raise DeployError("site/index.html is stale; run `zig build wasm-proofs` and `python3 tools/build_site.py`")


def meta_content(page: str, name: str) -> str:
    marker = f'<meta name="{name}" content="'
    start = page.find(marker)
    if start < 0:
        return ""
    start += len(marker)
    return html.unescape(page[start:page.index('"', start)])


def page_title(page: str) -> str:
    start = page.find("<title>")
    if start < 0:
        return "BeSpoke Engine"
    start += len("<title>")
    return html.unescape(page[start:page.index("</title>", start)])


def metadata(page: str, site_url: str | None) -> str:
    """Sharing tags built from the page's own title and description. URL tags only with a URL."""
    title = html.escape(page_title(page), quote=True)
    description = html.escape(meta_content(page, "description"), quote=True)
    lines = [
        f"  {HEAD_MARKER}",
        '  <meta name="theme-color" content="#0f172a">',
        '  <meta property="og:type" content="website">',
        f'  <meta property="og:title" content="{title}">',
        f'  <meta property="og:description" content="{description}">',
        '  <meta name="twitter:card" content="summary">',
        f'  <meta name="twitter:title" content="{title}">',
        f'  <meta name="twitter:description" content="{description}">',
    ]
    if site_url:
        url = html.escape(site_url, quote=True)
        lines.append(f'  <link rel="canonical" href="{url}">')
        lines.append(f'  <meta property="og:url" content="{url}">')
    return "\n".join(lines) + "\n"


def normalise_site_url(site_url: str | None) -> str | None:
    if not site_url:
        return None
    if not site_url.startswith("https://"):
        raise DeployError("--site-url must start with https://")
    return site_url if site_url.endswith("/") else site_url + "/"


def render_export(page: str, site_url: str | None) -> tuple[str, str]:
    """Returns (index.html, sw.js) for the export."""
    if page.count("</head>") != 1 or page.count("</body>") != 1:
        raise DeployError("site/index.html needs exactly one </head> and one </body>")
    if HEAD_MARKER in page or BODY_MARKER in page:
        raise DeployError("site/index.html already carries deploy markers; export from the repository page")
    out = page.replace("</head>", metadata(page, site_url) + "</head>", 1)
    out = out.replace("</body>", f"  {BODY_MARKER}\n" + REGISTRATION + "</body>", 1)
    digest = hashlib.sha256(out.encode("utf-8")).hexdigest()[:16]
    return out, SERVICE_WORKER.replace("__HASH__", digest)


def export(out_dir: Path, site_url: str | None, page_path: Path = SITE_HTML, check_current: bool = True) -> list[Path]:
    page = page_path.read_text(encoding="utf-8")
    if check_current:
        require_current_page(page)
    index, worker = render_export(page, normalise_site_url(site_url))
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    files = [("index.html", index), ("sw.js", worker)]
    if page_path == SITE_HTML and BARBS_HTML.exists():
        barbs = BARBS_HTML.read_text(encoding="utf-8")
        if check_current and load_build_site().render_barbs(barbs) != barbs:
            raise DeployError("site/barbs.html is stale; run `zig build wasm-proofs` and `python3 tools/build_site.py`")
        files.append(("barbs.html", barbs))
    for name, text in files:
        path = out_dir / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    exp = sub.add_parser("export", help="write dist/site/ for static hosting")
    exp.add_argument("--site-url", help="public https:// address, for canonical and OpenGraph tags")
    exp.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    try:
        for path in export(args.out, args.site_url):
            print(f"wrote {path} ({path.stat().st_size:,} bytes)")
        return 0
    except DeployError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
